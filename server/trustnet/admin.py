"""Admin cockpit: authentication (passkey + TOTP) and dashboard data.

Login = two factors, both required:
  1. a passkey (WebAuthn) with user verification: Touch ID on the Mac, Face ID on
     the iPhone; the passkey lives in Apple Passwords and syncs via the Apple Account;
  2. a 6-digit TOTP code generated by Apple Passwords.
Enrollment only works through a one-time setup link created on the server as root
(python -m trustnet.admin_cli setup-link), valid 30 minutes.
Sessions: random 256-bit token in an HttpOnly, Secure, SameSite=Strict cookie
scoped to /admindash; only its SHA-256 is stored. 5 failures in 15 minutes lock
the login for 15 minutes.
"""
import hashlib
import json
import secrets
import time

from . import totp, webauthn

SESSION_TTL = 12 * 3600
SETUP_TTL = 30 * 60
CHALLENGE_TTL = 300
LOCK_WINDOW, LOCK_MAX = 900, 5
COOKIE = "ta_admin"


class AuthError(Exception):
    def __init__(self, msg, status=401):
        super().__init__(msg)
        self.status = status


def _h(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


class Admin:
    def __init__(self, store, service, rp_id, origin, clock=time.time):
        self.store, self.service = store, service
        self.rp_id, self.origin = rp_id, origin
        self.clock = clock
        self.pending = {}   # nonce -> {kind, challenge, exp, ...} (in memory: one process)

    def now(self):
        return int(self.clock())

    # ------------------------------------------------------------------ storage helpers
    def _q(self, sql, args=(), one=False, commit=False):
        with self.store.lock:
            cur = self.store.db.execute(sql, args)
            rows = cur.fetchone() if one else cur.fetchall()
            if commit:
                self.store.db.commit()
            return rows

    def _kv(self, k, v=None):
        if v is None:
            r = self._q("SELECT v FROM admin_kv WHERE k = ?", (k,), one=True)
            return r[0] if r else None
        self._q("INSERT OR REPLACE INTO admin_kv (k, v) VALUES (?, ?)", (k, v), commit=True)

    def enrolled(self):
        has_key = self._q("SELECT count(*) FROM admin_credentials", one=True)[0] > 0
        return has_key and bool(self._kv("totp_secret"))

    def _fail(self, ip, what):
        self._q("INSERT INTO admin_failures (t, ip, what) VALUES (?, ?, ?)", (self.now(), ip or "", what), commit=True)

    def _locked(self):
        n = self._q("SELECT count(*) FROM admin_failures WHERE t >= ?", (self.now() - LOCK_WINDOW,), one=True)[0]
        return n >= LOCK_MAX

    def _new_pending(self, kind, **extra):
        now = self.now()
        for k in [k for k, p in self.pending.items() if p["exp"] < now]:
            del self.pending[k]
        nonce = secrets.token_urlsafe(18)
        self.pending[nonce] = dict(kind=kind, challenge=secrets.token_bytes(32), exp=now + CHALLENGE_TTL, **extra)
        return nonce, self.pending[nonce]

    def _take_pending(self, nonce, kind):
        p = self.pending.get(nonce or "")
        if not p or p["kind"] != kind or p["exp"] < self.now():
            raise AuthError("expired, please start again", 400)
        return p

    # ------------------------------------------------------------------ setup (one-time link)
    def create_setup_link(self):
        token = secrets.token_urlsafe(24)
        self._q("INSERT INTO admin_setup (token_hash, created_at, used_at) VALUES (?, ?, NULL)", (_h(token), self.now()), commit=True)
        return "%s/admindash/#setup=%s" % (self.origin, token)

    def _check_setup_token(self, token):
        r = self._q("SELECT created_at, used_at FROM admin_setup WHERE token_hash = ?", (_h(token or ""),), one=True)
        if not r or r[1] or self.now() - r[0] > SETUP_TTL:
            raise AuthError("setup link invalid, used or expired: create a new one on the server", 403)

    def setup_begin(self, body):
        token = body.get("setupToken")
        self._check_setup_token(token)
        nonce, p = self._new_pending("setup-create", token=token)
        existing = [webauthn.b64url_encode(r[0] if isinstance(r[0], bytes) else bytes.fromhex(r[0]))
                    for r in self._q("SELECT id FROM admin_credentials")]
        return {"nonce": nonce, "publicKey": {
            "challenge": webauthn.b64url_encode(p["challenge"]),
            "rp": {"id": self.rp_id, "name": "Trust Advisor Cockpit"},
            "user": {"id": webauthn.b64url_encode(b"trustadvisor-admin"), "name": "admin@" + self.rp_id,
                     "displayName": "Trust Advisor admin"},
            "pubKeyCredParams": [{"type": "public-key", "alg": -7}],
            "authenticatorSelection": {"authenticatorAttachment": "platform", "residentKey": "required",
                                       "requireResidentKey": True, "userVerification": "required"},
            "attestation": "none", "timeout": 120000,
            "excludeCredentials": [{"type": "public-key", "id": c} for c in existing],
        }}

    def setup_finish(self, body):
        p = self._take_pending(body.get("nonce"), "setup-create")
        self._check_setup_token(p["token"])
        try:
            reg = webauthn.verify_registration(body.get("credential") or {}, p["challenge"], self.origin, self.rp_id)
        except webauthn.WebAuthnError as e:
            raise AuthError("passkey not accepted: %s" % e, 400)
        self._q("INSERT OR REPLACE INTO admin_credentials (id, public_key, sign_count, created_at, last_used, label) "
                "VALUES (?, ?, ?, ?, NULL, ?)",
                (reg["credentialId"].hex(), reg["publicKey"], reg["signCount"], self.now(), str(body.get("label") or "passkey")[:40]),
                commit=True)
        del self.pending[body["nonce"]]
        if self._kv("totp_secret"):
            self._q("UPDATE admin_setup SET used_at = ? WHERE token_hash = ?", (self.now(), _h(p["token"])), commit=True)
            return {"done": True}
        secret = totp.new_secret()
        nonce, _ = self._new_pending("setup-totp", token=p["token"], secret=secret)
        self.pending[nonce]["exp"] = self.now() + 900
        return {"done": False, "nonce": nonce, "totpSecret": secret,
                "otpauth": totp.otpauth_uri(secret, "admin@" + self.rp_id)}

    def setup_totp(self, body):
        p = self._take_pending(body.get("nonce"), "setup-totp")
        self._check_setup_token(p["token"])
        step = totp.verify(p["secret"], body.get("code"), self.now())
        if step is None:
            raise AuthError("that code didn't match: check the Passwords app and try the current code", 400)
        self._kv("totp_secret", p["secret"])
        self._kv("totp_last_step", str(step))
        self._q("UPDATE admin_setup SET used_at = ? WHERE token_hash = ?", (self.now(), _h(p["token"])), commit=True)
        del self.pending[body["nonce"]]
        return {"done": True}

    # ------------------------------------------------------------------ login
    def login_begin(self, ip=None):
        if not self.enrolled():
            raise AuthError("no admin enrolled yet: open the one-time setup link", 403)
        if self._locked():
            raise AuthError("too many failed attempts: try again in 15 minutes", 429)
        nonce, p = self._new_pending("login", ip=ip, passkey_ok=False)
        return {"nonce": nonce, "publicKey": {"challenge": webauthn.b64url_encode(p["challenge"]), "rpId": self.rp_id,
                                              "userVerification": "required", "timeout": 120000, "allowCredentials": []}}

    def login_passkey(self, body, ip=None):
        if self._locked():
            raise AuthError("too many failed attempts: try again in 15 minutes", 429)
        p = self._take_pending(body.get("nonce"), "login")
        cred = body.get("credential") or {}
        cid = webauthn.b64url_decode(cred.get("rawId", "")).hex()
        row = self._q("SELECT public_key, sign_count FROM admin_credentials WHERE id = ?", (cid,), one=True)
        try:
            if not row:
                raise webauthn.WebAuthnError("unknown passkey")
            count = webauthn.verify_assertion(cred, p["challenge"], self.origin, self.rp_id, row[0], row[1])
        except webauthn.WebAuthnError as e:
            self._fail(ip, "passkey")
            raise AuthError("passkey not accepted: %s" % e)
        self._q("UPDATE admin_credentials SET sign_count = ?, last_used = ? WHERE id = ?", (count, self.now(), cid), commit=True)
        p["passkey_ok"] = True
        p["exp"] = self.now() + CHALLENGE_TTL
        return {"needCode": True}

    def login_code(self, body, ip=None):
        if self._locked():
            raise AuthError("too many failed attempts: try again in 15 minutes", 429)
        p = self._take_pending(body.get("nonce"), "login")
        if not p.get("passkey_ok"):
            raise AuthError("passkey first", 400)
        last = self._kv("totp_last_step")
        step = totp.verify(self._kv("totp_secret"), body.get("code"), self.now(), last_used_step=int(last) if last else None)
        if step is None:
            self._fail(ip, "totp")
            raise AuthError("wrong or reused code")
        self._kv("totp_last_step", str(step))
        del self.pending[body["nonce"]]
        token = secrets.token_urlsafe(32)
        self._q("INSERT INTO admin_sessions (token_hash, created_at, expires_at, ip) VALUES (?, ?, ?, ?)",
                (_h(token), self.now(), self.now() + SESSION_TTL, ip or ""), commit=True)
        return token

    def session_ok(self, token):
        if not token:
            return False
        r = self._q("SELECT expires_at FROM admin_sessions WHERE token_hash = ?", (_h(token),), one=True)
        return bool(r and r[0] > self.now())

    def logout(self, token):
        if token:
            self._q("DELETE FROM admin_sessions WHERE token_hash = ?", (_h(token),), commit=True)

    # ------------------------------------------------------------------ cockpit data
    # Aggregates only: no identifiers ever leave this method, and any group with
    # fewer than MIN_GROUP distinct people is folded into "Other (small groups)".
    MIN_GROUP = 10

    def _fold(self, rows, distinct=True):
        out, small = [], 0
        for k, n in rows:
            if distinct and n < self.MIN_GROUP:
                small += n
            else:
                out.append({"k": k if k is not None else "unknown", "n": n})
        if small:
            out.append({"k": "Other (small groups)", "n": small})
        return out

    def overview(self):
        now = self.now()
        q = self.store.q
        day = 86400

        def count(sql, args=()):
            return q(sql, args, one=True)[0] or 0

        def series(table, col, days=30, where=""):
            start = (now // day - days + 1) * day
            rows = q("SELECT (%s / 86400) * 86400 AS d, count(*) FROM %s WHERE %s >= ? %s GROUP BY d" % (col, table, col, where), (start,))
            got = {r[0]: r[1] for r in rows}
            return [{"t": start + i * day, "n": got.get(start + i * day, 0)} for i in range(days)]

        # observed population: one row per distinct (pseudonymous) character, latest attributes
        pop = "(SELECT member_h, max(class) AS class, max(race) AS race, max(faction) AS faction, max(level) AS level " \
              "FROM community_members GROUP BY member_h)"
        levels = lambda src: self._fold([("%d-%d" % (r[0], r[0] + 9), r[1]) for r in
                                         q("SELECT ((level - 1) / 10) * 10 + 1 AS b, count(*) FROM %s WHERE level IS NOT NULL GROUP BY b ORDER BY b" % src)])

        # community map: which classes play together (pairs inside the same group)
        pairs = {}
        for sid, classes in q("SELECT session_id, group_concat(class, '|') FROM community_members WHERE class IS NOT NULL GROUP BY session_id"):
            cl = sorted(set((classes or "").split("|")) - {""})
            for i in range(len(cl)):
                for j in range(i, len(cl)):
                    key = cl[i] + " + " + cl[j] if i != j else cl[i] + " + " + cl[i]
                    pairs[key] = pairs.get(key, 0) + 1
        top_pairs = sorted(pairs.items(), key=lambda kv: -kv[1])[:15]

        sizes = q("SELECT n, count(*) FROM (SELECT count(*) AS n FROM community_members GROUP BY session_id) GROUP BY n ORDER BY n")
        hours = {r[0]: r[1] for r in q("SELECT (a % 86400) / 3600 AS h, count(*) FROM community_sessions GROUP BY h")}

        versions, companions, locales, errors = {}, {}, {}, {}
        for (diag,) in q("SELECT diag FROM feedback WHERE diag IS NOT NULL"):
            try:
                d = json.loads(diag)
            except ValueError:
                continue
            for bucket, key in ((versions, d.get("addon")), (companions, d.get("companionVersion") or d.get("companion")), (locales, d.get("locale"))):
                if key:
                    bucket[key] = bucket.get(key, 0) + 1
            for e in d.get("errors") or []:
                msg = e.split(" ", 1)[-1][:160]
                errors[msg] = errors.get(msg, 0) + 1

        def top(d, n=12):
            return [{"k": k, "n": v} for k, v in sorted(d.items(), key=lambda kv: -kv[1])[:n]]

        demo = count("SELECT count(*) FROM uploaders WHERE id LIKE 'demo-%'") + count("SELECT count(*) FROM feedback WHERE id LIKE 'demo-%'")
        return {
            "generatedAt": now, "minGroup": self.MIN_GROUP, "demoRows": demo,
            "kpis": {
                "participants": count("SELECT count(*) FROM participants"),
                "active7d": count("SELECT count(*) FROM uploaders WHERE last_seen >= ?", (now - 7 * day,)),
                "layerBackup": count("SELECT count(*) FROM participants WHERE c_backup = 1"),
                "layerProfile": count("SELECT count(*) FROM participants WHERE c_profile = 1"),
                "layerCommunity": count("SELECT count(*) FROM participants WHERE c_community = 1"),
                "layerRecommend": count("SELECT count(*) FROM participants WHERE c_recommend = 1"),
                "backups": count("SELECT count(*) FROM backups"),
                "backupMB": round(count("SELECT sum(size) FROM backups") / 1048576.0, 1),
                "profiles": count("SELECT count(*) FROM profiles"),
                "linkedAccounts": count("SELECT count(DISTINCT account) FROM links"),
                "verifiedCharacters": count("SELECT count(*) FROM owned"),
                "communitySessions": count("SELECT count(*) FROM community_sessions"),
                "observedCharacters": count("SELECT count(DISTINCT member_h) FROM community_members"),
                "optedOut": count("SELECT count(*) FROM optout"),
                "feedbackNew": count("SELECT count(*) FROM feedback WHERE status = 'received'"),
                "feedbackTotal": count("SELECT count(*) FROM feedback"),
                "bugs": count("SELECT count(*) FROM feedback WHERE kind = 'bug'"),
                "ideas": count("SELECT count(*) FROM feedback WHERE kind = 'idea'"),
            },
            "series": {
                "newParticipants": series("uploaders", "created_at"),
                "communitySessions": series("community_sessions", "a"),
                "feedback": series("feedback", "received_at"),
            },
            "participants": {
                "faction": self._fold(q("SELECT faction, count(*) FROM participants GROUP BY faction ORDER BY count(*) DESC")),
                "race": self._fold(q("SELECT race, count(*) FROM participants GROUP BY race ORDER BY count(*) DESC")),
                "class": self._fold(q("SELECT class, count(*) FROM participants GROUP BY class ORDER BY count(*) DESC")),
                "levels": levels("participants"),
                "realm": self._fold(q("SELECT realm, count(*) FROM participants GROUP BY realm ORDER BY count(*) DESC LIMIT 15")),
                "locale": self._fold(q("SELECT locale, count(*) FROM participants GROUP BY locale ORDER BY count(*) DESC")),
                "region": self._fold(q("SELECT region, count(*) FROM links GROUP BY region ORDER BY count(*) DESC")),
            },
            "population": {
                "faction": self._fold(q("SELECT faction, count(*) FROM %s GROUP BY faction ORDER BY count(*) DESC" % pop)),
                "race": self._fold(q("SELECT race, count(*) FROM %s GROUP BY race ORDER BY count(*) DESC" % pop)),
                "class": self._fold(q("SELECT class, count(*) FROM %s GROUP BY class ORDER BY count(*) DESC" % pop)),
                "levels": levels(pop),
            },
            "community": {
                "classPairs": self._fold(top_pairs, distinct=False),
                "places": self._fold(q("SELECT place, count(*) FROM community_sessions GROUP BY place ORDER BY count(*) DESC LIMIT 12"), distinct=False),
                "byType": self._fold(q("SELECT type, count(*) FROM community_sessions GROUP BY type ORDER BY count(*) DESC"), distinct=False),
                "byHour": [{"k": "%02d" % h, "n": hours.get(h, 0)} for h in range(24)],
                "groupSizes": [{"k": str(r[0]), "n": r[1]} for r in sizes],
            },
            "feedback": {
                "byStatus": [{"k": r[0], "n": r[1]} for r in q("SELECT status, count(*) FROM feedback GROUP BY status ORDER BY count(*) DESC")],
                "addonVersions": top(versions), "companions": top(companions), "locales": top(locales), "topErrors": top(errors, 8),
            },
        }

    def feedback_list(self, status=None):
        return self.store.list_feedback(status or None, 500)
